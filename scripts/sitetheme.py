"""One theme, one page shell, for every page the site publishes.

The site is generated by three scripts that grew at different times, and it
looked like it: `render-comparisons.py` had a full design system with dark
mode, an animated hero and a card grid, `render-benchmarks.py` had a smaller
variation on the same idea, and `coverage-dashboard.py` opened its own
stylesheet with a comment calling itself "a deliberately dumb page" -- black
on white, no dark mode, borders at `1px solid #ccc`. A reader moving between
them by the nav links crossed two visual identities in three clicks.

So the tokens and the shell live here and the pages import them. The rule
that follows is the useful part: **a page may add CSS, and may not restate
these.** A colour that appears literally in a page generator is a colour that
will drift from the other two, because nothing makes them move together.

Nothing here is page-specific. The heatmap's cell styling, the dashboard's
bars and the animated architecture diagram all stay with the page that owns
them -- shared means shared, not "everything, somewhere".
"""

