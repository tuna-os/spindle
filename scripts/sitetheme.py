# The site's pages, in the order the nav lists them. One tuple per page so a
# new page cannot be added to one nav and forgotten in the other two.
PAGES = [
    ("comparisons.html", "Spindle vs the field"),
    ("dashboard.html", "Coverage"),
    ("index.html", "Micro-benchmarks"),
]


def nav(active: str, sections: list[tuple[str, str]] | None = None,
        repository: str = "tuna-os/spindle") -> str:
    """The shared nav, marking whichever page is rendering it.

    `sections` are the current page's own in-page anchors, rendered after a
    separator. They are per-page because they *are* per-page -- a long page
    earns a table of contents and a short one does not -- but the site links
    beside them stay identical everywhere, which is the part that was
    drifting.
    """
    links = []
    for href, label in PAGES:
        current = ' aria-current="page"' if href == active else ""
        links.append(f'<a href="./{href}"{current}>{html.escape(label)}</a>')
    for anchor, label in sections or []:
        links.append(f'<a class="sect" href="{anchor}">{html.escape(label)}</a>')
    # Parameterised for the same reason the footer's link is: this one is
    # generated for whatever repository the page was told about.
    links.append(
        f'<a class="sect" href="https://github.com/{html.escape(repository)}">GitHub</a>'
    )
    inner = "".join(links)
    return f'<nav><div class="inner"><span class="brand">Spindle</span>{inner}</div></nav>'


def head(title: str, extra_css: str = "") -> str:
    """Everything above the body content: meta, title, tokens, base, page CSS."""
    return (
        '<!doctype html>\n<html lang="en">\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f"<title>{html.escape(title)}</title>\n"
        f"<style>{TOKENS}{BASE}{extra_css}</style>\n"
    )


def footer(note: str = "", repository: str = "tuna-os/spindle") -> str:
    """The shared footer. `note` is per-page provenance, already escaped.

    `repository` is a parameter and not a constant because one page is
    generated for whatever repository it is told about, and the tooling check
    enforces that: the source link was hardcoded once and went on pointing at
    the previous owner from the moment the project moved. A shared footer is
    exactly the place that mistake would come back, so it does not get to
    know the answer on its own.
    """
    source = (
        f'<a href="https://github.com/{html.escape(repository)}">'
        f"{html.escape(repository)}</a>"
    )
    extra = f" · {note}" if note else ""
    return f"<footer>Generated from {source}{extra}</footer>"
